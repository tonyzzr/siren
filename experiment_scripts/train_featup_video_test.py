class VideoAndFlowFitting(Dataset):
    '''
        This dataset loads mock video and flow field.
        The mock video is generated by prepare_mock_video.py.
        See verify_mock_video.py for more details.

        There is no intensity/color features in the input.


        Every time, we sample a frame from the video, and the corresponding flow field.
        (we may need to write another dataset if we want to sample the entire video)
    '''
    def __init__(self, data_path):
        super().__init__()
        self.data_path = data_path
        self.video_dict = torch.load(data_path)
        self.flow_fields = self.video_dict['flow_fields'] # currently (f, 2, h, w)
        self.video_frames = self.video_dict['video_frames'].unsqueeze(1) # make it (f, 1, h, w)
        self.source_image = self.video_dict['source_image']
        self.motion_type = self.video_dict['motion_type']

        print("self.video_dict.keys(): ", self.video_dict.keys())
        print("self.video_frames.shape: ", self.video_frames.shape)
        print("self.flow_fields.shape: ", self.flow_fields.shape)

        self.f, c, h, w = self.video_frames.shape
        assert h == w == 224

        self.spatial_coords = get_mgrid(h, 2)
        print("self.spatial_coords.shape: ", self.spatial_coords.shape)
        self.temporal_coords = torch.linspace(-1, 1, self.f)
        print("self.temporal_coords.shape: ", self.temporal_coords.shape)
        self.pixels = self.video_frames.view(self.f, -1, c)
        print("self.pixels.shape: ", self.pixels.shape)

    def __len__(self):
        return self.f
    
    def __getitem__(self, idx):
        if idx >= self.f:
            raise IndexError
        
        # pixel_data = self.pixels[idx] # in shape of (224*224, 1)
        spatial_coords = self.spatial_coords # in shape of (224*224, 2)
        temporal_coords = self.temporal_coords[idx] * torch.ones_like(spatial_coords[..., :1]) # in shape of (224*224, 1)
        combined_input_features = torch.cat([spatial_coords, 
                                             temporal_coords, ], dim=1)


        flow_field_2d = self.flow_fields[idx] # in shape of (2, 224, 224)

        return combined_input_features, flow_field_2d, self.video_frames[idx]

